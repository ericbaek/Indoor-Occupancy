def test_estimate_zone_centre_when_two_anchors_close(monkeypatch):
    """Two anchors within threshold → candidate = centre; after hold_seconds it becomes stable."""
    monkeypatch.setattr(_svc, "_tag_state", {})
    threshold = ble_config.BLE_SETTINGS["centre_rssi_threshold_db"]
    rssi = {"anchor-left": -50, "anchor-right": -50 - threshold + 1}  # diff < threshold

    t1 = _ts_now()
    # First call: establishes candidate
    estimate_zone("TAG-Z2", rssi, None, t1)
    # Call again after hold time
    t2 = _ts_future(ble_config.BLE_SETTINGS["zone_hold_seconds"] + 0.1)
    zone = estimate_zone("TAG-Z2", rssi, None, t2)
    assert zone == "centre"


def test_estimate_zone_hysteresis_prevents_rapid_flap(monkeypatch):
    """Zone should not flip every single reading; old zone is retained until hold time elapsed."""
    monkeypatch.setattr(_svc, "_tag_state", {})
    hold = ble_config.BLE_SETTINGS["zone_hold_seconds"]

    rssi_left = {"anchor-left": -45, "anchor-right": -75, "anchor-back": -75}
    rssi_right = {"anchor-right": -45, "anchor-left": -75, "anchor-back": -75}

    t = _ts_now()
    # Stabilise in "left" zone (need to get past hold time)
    estimate_zone("TAG-Z3", rssi_left, None, t)
    t_stable = _ts_future(hold + 0.5)
    stable = estimate_zone("TAG-Z3", rssi_left, None, t_stable)
    assert stable == "left"

    # Immediately flip to right readings — should NOT change yet
    zone_after_flip = estimate_zone("TAG-Z3", rssi_right, None, _ts_future(hold + 0.6))
    assert zone_after_flip == "left"  # hysteresis holds


def test_estimate_zone_transitions_after_hold_time(monkeypatch):
    monkeypatch.setattr(_svc, "_tag_state", {})
    hold = ble_config.BLE_SETTINGS["zone_hold_seconds"]

    rssi_left = {"anchor-left": -45, "anchor-right": -75, "anchor-back": -75}
    rssi_right = {"anchor-right": -45, "anchor-left": -75, "anchor-back": -75}

    t = _ts_now()
    estimate_zone("TAG-Z4", rssi_left, None, t)
    estimate_zone("TAG-Z4", rssi_left, None, _ts_future(hold + 0.1))

    # Now move to right zone consistently for longer than hold time
    t_right_start = _ts_future(hold + 0.2)
    estimate_zone("TAG-Z4", rssi_right, None, t_right_start)
    t_right_done = (
        datetime.now(timezone.utc) + timedelta(seconds=hold * 2 + 1.0)
    ).isoformat()
    final_zone = estimate_zone("TAG-Z4", rssi_right, None, t_right_done)
    assert final_zone == "right"


