def test_distance_at_reference_equals_one_metre():
    # reference_rssi_at_1m = -50.0 for anchor-left
    dist = rssi_to_distance(-50.0, "anchor-left")
    assert abs(dist - 1.0) < 0.001


def test_distance_stronger_rssi_gives_shorter_distance():
    dist = rssi_to_distance(-40.0, "anchor-left")
    assert dist < 1.0


def test_distance_weaker_rssi_gives_longer_distance():
    dist = rssi_to_distance(-60.0, "anchor-left")
    assert dist > 1.0


def test_distance_invalid_anchor_returns_none():
    assert rssi_to_distance(-55.0, "unknown-anchor") is None


def test_distance_clamped_to_configured_max():
    max_d = ble_config.BLE_SETTINGS["max_distance_metres"]
    dist = rssi_to_distance(-120.0, "anchor-left")
    assert dist == max_d


def test_distance_positive():
    dist = rssi_to_distance(-65.0, "anchor-right")
    assert dist > 0


def test_distance_uses_per_anchor_calibration():
    # anchor-left ref=-50.0, anchor-back ref=-49.0
    d_left = rssi_to_distance(-50.0, "anchor-left")
    d_back = rssi_to_distance(-49.0, "anchor-back")
    # Both at their own reference RSSI → both should be 1.0 m
    assert abs(d_left - 1.0) < 0.001
    assert abs(d_back - 1.0) < 0.001


